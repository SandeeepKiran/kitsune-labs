// Bug Finder: where did a bot conversation go wrong? Rules always run (no key needed);
// with a key, AI adds a second opinion, a summary and the customer's sentiment.
import { BUG_TYPES, BUG_TYPE_IDS, expectedBehaviour, findBugs, type BugType, type Finding, type Severity } from '../shared/analysis.ts';
import { keyEntry, loadAnswerKey } from '../shared/answer-key.ts';
import { parseAiJson } from '../shared/ai.ts';
import { conversationsFrom, type Conversation } from '../shared/conversations.ts';
import { el } from '../shared/dom.ts';
import { baseName, downloadCsv, downloadJson, downloadText } from '../shared/export.ts';
import { downloadWorkbook } from '../shared/files.ts';
import { checkOption, optionChecks } from '../shared/options.ts';
import { aiChip, annotatedTurns, answerKeyCheck, dataTable, findingList, rulesChip, section, stats } from '../shared/results.ts';
import type { AiSession, ToolDefinition } from '../shared/tool-page.ts';
import type { Turn } from '../shared/transcript.ts';

const showFixes = checkOption('show-fixes', 'Show fix hints', true);
const showTurns = checkOption('show-turns', 'Show the annotated conversation', true);

const SEVERITIES: Severity[] = ['high', 'medium', 'low'];

interface AiReview {
  summary?: string;
  sentiment?: { start?: string; end?: string };
  findings?: { type?: string; turn?: number; severity?: string; title?: string; evidence?: string; fix?: string }[];
}

const numbered = (turns: Turn[]) => turns.map((t) => `${t.index} [${t.role}] ${t.speaker}: ${t.text.replace(/\s+/g, ' ')}`).join('\n');

async function aiReview(ai: AiSession, turns: Turn[]): Promise<AiReview> {
  const reply = await ai.ask({
    system: 'You are a senior QA engineer who reviews conversations between customers and a support bot. '
      + 'You find defects in the bot\'s behaviour, with evidence. Answer with JSON only.',
    prompt: [
      'Known bug types (use one when it fits, or a short snake_case type of your own):',
      ...BUG_TYPE_IDS.map((id) => `- ${id} (${BUG_TYPES[id].severity}): ${BUG_TYPES[id].meaning}`),
      'One normal re-prompt is not a bug. Report a bug on the bot turn where it shows.',
      'Return: {"summary": "2-3 plain sentences", "sentiment": {"start": "positive|neutral|negative", "end": "positive|neutral|negative"},',
      '"findings": [{"type": "", "turn": 0, "severity": "high|medium|low", "title": "", "evidence": "", "fix": ""}]}',
      'Conversation (turn number, role, speaker, text):',
      numbered(turns),
    ].join('\n'),
    json: true,
  });
  return parseAiJson<AiReview>(reply.text);
}

/** AI findings that match a rules finding (same type, turn within 1) confirm it; the rest are added. */
function merge(rules: Finding[], review: AiReview, turnCount: number): Finding[] {
  const merged = rules.map((f) => ({ ...f }));
  for (const raw of review.findings ?? []) {
    const type = String(raw.type ?? '').trim().slice(0, 40) || 'other';
    const turn = Math.round(Number(raw.turn));
    if (!Number.isFinite(turn) || turn < 1 || turn > turnCount) continue;
    const match = merged.find((f) => f.source === 'rules' && f.type === type && Math.abs(f.turn - turn) <= 1);
    if (match) { match.confirmed = true; continue; }
    const info = BUG_TYPES[type as BugType];
    merged.push({
      type, turn, source: 'ai',
      severity: SEVERITIES.includes(raw.severity as Severity) ? (raw.severity as Severity) : info?.severity ?? 'medium',
      title: String(raw.title ?? info?.title ?? type).slice(0, 80),
      evidence: String(raw.evidence ?? '').slice(0, 400),
      fix: String(raw.fix ?? info?.fix ?? '').slice(0, 300),
    });
  }
  return merged.sort((a, b) => a.turn - b.turn);
}

function bugReports(conversation: Conversation, findings: Finding[]): string {
  const lines = [`# Bug reports: ${conversation.id}`, '', 'Generated by Kitsune Labs Bug Finder. All Mousy data is invented.', ''];
  findings.forEach((f, i) => {
    const said = conversation.turns.filter((t) => t.role === 'customer' && t.index < f.turn);
    const actual = conversation.turns.find((t) => t.index === f.turn)?.text ?? '';
    lines.push(
      `## ${i + 1}. ${f.title} (turn ${f.turn})`, '',
      `- Severity: ${f.severity}`, `- Type: ${f.type}`, `- Found by: ${f.source === 'ai' ? 'AI-assisted review' : 'rules'}${f.confirmed ? ' (AI agrees)' : ''}`, '',
      '### Steps', '',
      '1. Start a new conversation with the bot.',
      ...said.map((t, n) => `${n + 2}. Say: "${t.text.replace(/\s+/g, ' ')}"`), '',
      '### Expected', '', expectedBehaviour(f), '',
      '### Actual', '', `The bot says: "${actual.replace(/\s+/g, ' ')}"`, '',
      '### Evidence', '', f.evidence, '',
      ...(f.fix ? ['### Fix hint', '', f.fix, ''] : []),
    );
  });
  if (!findings.length) lines.push('No bugs found.', '');
  return lines.join('\n');
}

function exportShape(items: { conversation: Conversation; findings: Finding[] }[], aiUsed: boolean) {
  return {
    about: 'Bug Finder results. Report Builder and Email Templates can read this file.',
    generated_by: 'Kitsune Labs Bug Finder',
    ai_assisted: aiUsed,
    conversations: items.map(({ conversation, findings }) => ({
      conversation_id: conversation.id,
      channel: conversation.row?.channel ?? 'unknown',
      outcome: conversation.row?.outcome ?? 'unknown',
      bugs: findings.map((f) => ({ type: f.type, turn: f.turn, severity: f.severity, title: f.title, evidence: f.evidence, fix: f.fix, source: f.source })),
    })),
  };
}

const severityLine = (findings: Finding[]) =>
  SEVERITIES.map((s) => `${findings.filter((f) => f.severity === s).length} ${s}`).join(' · ');

export const definition: ToolDefinition = {
  answerLabel: 'Findings',
  heroHint: 'Paste one conversation, or drop a transcript, .csv, .xlsx or .zip',
  mapping: true,
  aiNote: 'AI reviews the conversation as a second opinion, and adds a summary and the customer\'s sentiment.',
  options: () => optionChecks('Show', showFixes, showTurns),
  async run({ input, mapping, ai, log, progress, tick }) {
    const conversations = conversationsFrom(input, mapping);
    if (!conversations.length) {
      return {
        answer: { value: '0', label: 'Findings', sub: 'No turns found. Check the line format.' },
        results: el('div', { class: 'empty' }, el('p', { class: 'empty__title' }, 'No turns found.'),
          el('p', {}, 'Each line should look like "[00:00:02] Mousy Assist: Hi" or "Customer: Hi".')),
        logLine: 'Parsed 0 turns',
        exports: [],
      };
    }
    const key = await loadAnswerKey();
    const stem = baseName(input.name === 'pasted text' ? 'conversation' : input.name);
    const strip = (fs: Finding[]) => (showFixes.checked ? fs : fs.map((f) => ({ ...f, fix: '' })));

    // -- one conversation: full review ---------------------------------------------------
    if (conversations.length === 1) {
      const conversation = conversations[0];
      let findings = findBugs(conversation.turns);
      let review: AiReview | null = null;
      if (ai.ready) {
        try {
          review = await aiReview(ai, conversation.turns);
          findings = merge(findings, review, conversation.turns.length);
        } catch (error) {
          log.add(`AI review skipped: ${(error as Error).message} Rules results are shown.`, 'warn');
        }
      }
      const entry = keyEntry(key, conversation);
      const rulesOnly = findings.filter((f) => f.source === 'rules');
      const aiBox = review ? el('div', { class: 'ai-output', 'data-testid': 'ai-summary' },
        aiChip(`AI-assisted · ${ai.label}`),
        review.summary ? el('p', {}, String(review.summary).slice(0, 800)) : null,
        review.sentiment ? el('p', {}, el('strong', {}, 'Customer sentiment: '),
          `${review.sentiment.start ?? '?'} at the start, ${review.sentiment.end ?? '?'} at the end.`) : null,
      ) : null;
      return {
        answer: {
          value: String(findings.length),
          label: findings.length === 1 ? 'Finding' : 'Findings',
          sub: `${severityLine(findings)} · ${conversation.turns.length} turns`,
        },
        results: el('div', {},
          entry ? answerKeyCheck(rulesOnly, entry) : null,
          aiBox,
          section('Findings', review ? aiChip('Rules + AI') : rulesChip(), findingList(strip(findings))),
          showTurns.checked ? section('Conversation', annotatedTurns(conversation.turns, findings)) : null,
        ),
        logLine: `Parsed ${conversation.turns.length} turns · ${findings.length} findings`,
        exports: [
          { label: 'Download .json', run: () => downloadJson(`${stem}_findings.json`, exportShape([{ conversation, findings }], Boolean(review))) },
          { label: 'Download .csv', run: () => downloadCsv(`${stem}_findings.csv`, findings.map((f) => ({ conversation_id: conversation.id, ...f })), ['conversation_id', 'turn', 'type', 'severity', 'title', 'evidence', 'fix', 'source']) },
          { label: 'Download bug reports (.md)', run: () => downloadText(`${stem}_bug_reports.md`, bugReports(conversation, findings), 'text/markdown') },
        ],
      };
    }

    // -- many conversations: rules on each, one table ------------------------------------
    if (ai.ready) log.add('AI review runs on one conversation at a time. Open a single transcript to use it.');
    const items: { conversation: Conversation; findings: Finding[] }[] = [];
    for (const [i, conversation] of conversations.entries()) {
      items.push({ conversation, findings: findBugs(conversation.turns) });
      if (i % 10 === 0) { progress(i + 1, conversations.length, `${i + 1} of ${conversations.length} conversations`); await tick(); }
    }
    progress(conversations.length, conversations.length, `${conversations.length} of ${conversations.length} conversations`);
    const all = items.flatMap((i) => i.findings);
    let checked = 0;
    let exact = 0;
    for (const { conversation, findings } of items) {
      const entry = keyEntry(key, conversation);
      if (!entry) continue;
      checked += 1;
      const want = entry.bugs.map((b) => `${b.type}@${b.turn}`).sort().join();
      if (findings.map((f) => `${f.type}@${f.turn}`).sort().join() === want) exact += 1;
    }
    const rows = items.map(({ conversation, findings }) => ({
      conversation_id: conversation.id,
      turns: conversation.turns.length,
      findings: findings.length,
      worst: findings.some((f) => f.severity === 'high') ? 'high' : findings.some((f) => f.severity === 'medium') ? 'medium' : findings.length ? 'low' : 'clean',
      types: findings.map((f) => `${f.type}@${f.turn}`).join(' '),
    }));
    const findingRows = items.flatMap(({ conversation, findings }) => findings.map((f) => ({ conversation_id: conversation.id, turn: f.turn, type: f.type, severity: f.severity, evidence: f.evidence, fix: f.fix })));
    return {
      answer: { value: String(all.length), label: 'Findings', sub: `in ${conversations.length} conversations · ${severityLine(all)}` },
      results: el('div', {},
        checked ? el('div', { class: 'key-check', 'data-testid': 'key-check' },
          el('span', {}, `${exact} of ${checked} conversations match the Mousy answer key exactly.`)) : null,
        stats([
          { label: 'Conversations', value: conversations.length },
          { label: 'Clean', value: rows.filter((r) => r.worst === 'clean').length, tone: 'pass' },
          { label: 'High', value: all.filter((f) => f.severity === 'high').length, tone: 'fail' },
          { label: 'Medium', value: all.filter((f) => f.severity === 'medium').length, tone: 'warn' },
          { label: 'Low', value: all.filter((f) => f.severity === 'low').length, tone: 'warn' },
        ]),
        section('Per conversation', rulesChip(), dataTable({ columns: ['conversation_id', 'turns', 'findings', 'worst', 'types'], rows, mono: ['conversation_id', 'types'], testId: 'bulk-findings' })),
      ),
      logLine: `Checked ${conversations.length} conversations · ${all.length} findings`,
      exports: [
        { label: 'Download .xlsx', run: () => downloadWorkbook(`${stem}_findings.xlsx`, [{ name: 'per_conversation', rows }, { name: 'findings', rows: findingRows }]) },
        { label: 'Download .csv', run: () => downloadCsv(`${stem}_findings.csv`, findingRows) },
        { label: 'Download .json', run: () => downloadJson(`${stem}_findings.json`, exportShape(items, false)) },
      ],
    };
  },
};
